"""Incident lifecycle: states and the allowed-transition map (ARCHITECTURE.md state machine)."""

from enum import StrEnum


class State(StrEnum):
    CREATED = "CREATED"
    SNAPSHOT_LOCKED = "SNAPSHOT_LOCKED"
    EVIDENCE_COLLECTED = "EVIDENCE_COLLECTED"
    CONTEXT_RETRIEVED = "CONTEXT_RETRIEVED"
    DIAGNOSED = "DIAGNOSED"
    INCONCLUSIVE = "INCONCLUSIVE"
    PATCH_PROPOSED = "PATCH_PROPOSED"
    VALIDATING = "VALIDATING"
    VERIFIED = "VERIFIED"
    UNVERIFIED = "UNVERIFIED"
    REVIEW_PENDING = "REVIEW_PENDING"
    REVIEWED = "REVIEWED"
    CLOSED = "CLOSED"


S = State
ALLOWED: dict[State, set[State]] = {
    S.CREATED: {S.SNAPSHOT_LOCKED},
    S.SNAPSHOT_LOCKED: {S.EVIDENCE_COLLECTED},
    S.EVIDENCE_COLLECTED: {S.CONTEXT_RETRIEVED},
    S.CONTEXT_RETRIEVED: {S.DIAGNOSED, S.INCONCLUSIVE},
    # DIAGNOSED -> REVIEW_PENDING: runtime_dependency (no patch).
    # INCONCLUSIVE -> REVIEW_PENDING: insufficient_evidence.
    S.DIAGNOSED: {S.PATCH_PROPOSED, S.REVIEW_PENDING},
    S.INCONCLUSIVE: {S.REVIEW_PENDING},
    S.PATCH_PROPOSED: {S.VALIDATING},
    S.VALIDATING: {S.VERIFIED, S.UNVERIFIED},
    S.VERIFIED: {S.REVIEW_PENDING},
    S.UNVERIFIED: {S.REVIEW_PENDING},
    S.REVIEW_PENDING: {S.REVIEWED},
    S.REVIEWED: {S.CLOSED},
    S.CLOSED: set(),
}
